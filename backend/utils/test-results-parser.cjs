    async getTestExecutionMetrics() {
        try {
            console.log('[TestResultsParser] Getting test execution metrics...');
            const testResults = await this.parseTestResults();
            
            console.log('[TestResultsParser] Found', testResults.length, 'test results');
            
            const metrics = {
                totalTests: testResults.length,
                passed: testResults.filter(t => t.status === 'passed').length,
                failed: testResults.filter(t => t.status === 'failed').length,
                skipped: testResults.filter(t => t.status === 'skipped').length,
                totalDuration: testResults.reduce((sum, t) => sum + t.duration, 0),
                averageDuration: 0,
                stepCount: testResults.reduce((sum, t) => sum + t.steps.length, 0),
                pageCoverage: new Set(),
                actionCoverage: new Set(),
                testSuites: new Set()
            };

            // Calculate averages
            if (metrics.totalTests > 0) {
                metrics.averageDuration = metrics.totalDuration / metrics.totalTests;
            }

            // Collect coverage data
            for (const test of testResults) {
                test.pages.forEach(page => metrics.pageCoverage.add(page));
                test.steps.forEach(step => metrics.actionCoverage.add(step.action));
                if (test.epic) metrics.testSuites.add(test.epic);
            }

            // Convert Sets to Arrays
            metrics.pageCoverage = Array.from(metrics.pageCoverage);
            metrics.actionCoverage = Array.from(metrics.actionCoverage);
            metrics.testSuites = Array.from(metrics.testSuites);

            console.log('[TestResultsParser] Metrics calculated:', {
                totalTests: metrics.totalTests,
                passed: metrics.passed,
                failed: metrics.failed
            });

            return {
                metrics,
                testResults
            };
        } catch (error) {
            console.error('[TestResultsParser] Error getting test execution metrics:', error);
            console.error('[TestResultsParser] Stack:', error.stack);
            return { metrics: {}, testResults: [] };
        }
    }
